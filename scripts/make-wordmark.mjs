// Dev-only: turns the footer wordmark into SVG letter outlines for the "drawing" animation.
// Usage: node scripts/make-wordmark.mjs <path to CormorantGaramond-Medium.ttf> [text]
// Cormorant Garamond is under the SIL Open Font License, which allows converting its outlines into graphics.
import { writeFileSync } from "node:fs";
import opentype from "opentype.js";

const [fontPath, text = "Sawari"] = process.argv.slice(2);
if (!fontPath) throw new Error("Pass the path to the Cormorant Garamond Medium TTF");
const font = opentype.loadSync(fontPath);
const SIZE = 200;
// same tracking as the footer's text (-0.04em)
const paths = font.getPaths(text, 0, SIZE, SIZE, { kerning: true, letterSpacing: -0.04 });
const glyphs = [...text].map((ch, i) => ({ ch, d: paths[i].toPathData(1), box: paths[i].getBoundingBox() })).filter((g) => g.d);
const minX = Math.min(...glyphs.map((g) => g.box.x1)), maxX = Math.max(...glyphs.map((g) => g.box.x2));
const minY = Math.min(...glyphs.map((g) => g.box.y1)), maxY = Math.max(...glyphs.map((g) => g.box.y2));
const pad = 4;
const viewBox = [minX - pad, minY - pad, maxX - minX + pad * 2, maxY - minY + pad * 2].map((n) => Math.round(n * 10) / 10).join(" ");
const out = `// Generated by scripts/make-wordmark.mjs from Cormorant Garamond Medium (SIL Open Font License). Do not edit by hand.
export const WORDMARK = ${JSON.stringify({ text, viewBox, letters: glyphs.map(({ ch, d }) => ({ ch, d })) }, null, 2)} as const;
`;
writeFileSync("src/components/footer/wordmark-paths.ts", out);
console.log(`${glyphs.length} letters, viewBox ${viewBox}, ${out.length} bytes`);
