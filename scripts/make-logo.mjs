// Dev-only: splits the Seto Durbar logo SVG into the emblem and the lettering, as plain path data, so the header
// and the preloader can draw them in the theme's colours. Usage: node scripts/make-logo.mjs <path to logo .svg>
import { readFileSync, writeFileSync } from "node:fs";

const [file] = process.argv.slice(2);
if (!file) throw new Error("Pass the path to the logo SVG");
const svg = readFileSync(file, "utf8");
const r1 = (n) => Math.round(n * 10) / 10;
const attr = (tag, name) => Number(new RegExp(String.raw`\s${name}="([^"]+)"`).exec(tag)?.[1]);

// every absolute M/L/Q/H/V/Z path: round the numbers, shift by (dx, dy) and track the bounds (control points included)
function normalize(d, dx = 0, dy = 0, box) {
  const out = [];
  let x = 0, y = 0;
  for (const [, cmd, args] of d.matchAll(/([MLQHVZ])([^MLQHVZ]*)/g)) {
    const n = args.trim() ? args.trim().split(/[\s,]+/).map(Number) : [];
    if (cmd === "H") { x = n[0]; out.push(`H${r1(x - dx)}`); box.x1 = Math.min(box.x1, x); box.x2 = Math.max(box.x2, x); continue; }
    if (cmd === "V") { y = n[0]; out.push(`V${r1(y - dy)}`); box.y1 = Math.min(box.y1, y); box.y2 = Math.max(box.y2, y); continue; }
    const pts = [];
    for (let i = 0; i < n.length; i += 2) {
      [x, y] = [n[i], n[i + 1]];
      box.x1 = Math.min(box.x1, x); box.x2 = Math.max(box.x2, x); box.y1 = Math.min(box.y1, y); box.y2 = Math.max(box.y2, y);
      pts.push(`${r1(x - dx)} ${r1(y - dy)}`);
    }
    out.push(cmd + pts.join(" "));
  }
  return out.join("");
}
const emptyBox = () => ({ x1: Infinity, y1: Infinity, x2: -Infinity, y2: -Infinity });
const viewBox = (b, pad) => [b.x1 - pad, b.y1 - pad, b.x2 - b.x1 + pad * 2, b.y2 - b.y1 + pad * 2].map(r1).join(" ");

// the emblem: the first <g>, in its own 200-unit space; shapes become paths so each one can be stroke-drawn
const emblemSrc = /<g transform[^>]*>([\s\S]*?)<\/g>/.exec(svg)[1];
const eBox = emptyBox();
const emblem = [...emblemSrc.matchAll(/<(polygon|circle|rect|path)\b[^>]*>/g)].map(([tag, kind]) => {
  const gold = /fill="#E6D3A3"/i.test(tag);
  let d;
  if (kind === "polygon") d = "M" + /points="([^"]+)"/.exec(tag)[1].trim().split(/\s+/).map((p) => p.replace(",", " ")).join("L") + "Z";
  else if (kind === "circle") { const [cx, cy, r] = ["cx", "cy", "r"].map((a) => attr(tag, a)); d = `M${cx - r} ${cy}A${r} ${r} 0 1 0 ${cx + r} ${cy}A${r} ${r} 0 1 0 ${cx - r} ${cy}Z`; eBox.y1 = Math.min(eBox.y1, cy - r); }
  else if (kind === "rect") { const [x, y, w, h] = ["x", "y", "width", "height"].map((a) => attr(tag, a)); d = `M${x} ${y}H${x + w}V${y + h}H${x}Z`; }
  else d = / d="([^"]+)"/.exec(tag)[1].replace(/\s*([MLZ])\s*/g, "$1").trim();
  if (kind !== "circle") normalize(d.replace(/A[^A-Z]*/g, ""), 0, 0, eBox); // bounds only
  return { d, gold, evenodd: /evenodd/.test(tag) };
});

// the lettering: the second <g>, shifted so it starts near 0,0
const textSrc = [...svg.matchAll(/<g fill[^>]*>([\s\S]*?)<\/g>/g)][0][1];
const ds = [...textSrc.matchAll(/ d="([^"]+)"/g)].map((m) => m[1]);
const tBox = emptyBox();
ds.forEach((d) => normalize(d, 0, 0, tBox));
const ox = Math.floor(tBox.x1), oy = Math.floor(tBox.y1);
const lettering = ds.map((d) => normalize(d, ox, oy, emptyBox()));
const tShift = { x1: tBox.x1 - ox, y1: tBox.y1 - oy, x2: tBox.x2 - ox, y2: tBox.y2 - oy };

const out = `// Generated by scripts/make-logo.mjs from the Seto Durbar logo SVG. Do not edit by hand.
export const EMBLEM = ${JSON.stringify({ viewBox: viewBox(eBox, 2), shapes: emblem })} as const;
export const LETTERING = ${JSON.stringify({ viewBox: viewBox(tShift, 1), paths: lettering })} as const;
`;
writeFileSync("src/components/logo/logo-paths.ts", out);
console.log(`emblem ${emblem.length} shapes ${viewBox(eBox, 2)}, lettering ${lettering.length} paths ${viewBox(tShift, 1)}, ${out.length} bytes`);
